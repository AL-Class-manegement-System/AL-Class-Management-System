<script>
    // --- Toast Notification Logic ---
    window.addEventListener('load', () => {
        const urlParams = new URLSearchParams(window.location.search);
        const status = urlParams.get('status');
        const msg = urlParams.get('msg');

        if (status && msg) {
            showToast(status, msg);
            // Clean URL
            const newUrl = window.location.protocol + "//" + window.location.host + window.location.pathname;
            window.history.pushState({ path: newUrl }, '', newUrl);
        }
    });

    function showToast(status, msg) {
        const toast = document.getElementById('toast-notification');
        const messageEl = document.getElementById('toast-message');
        const titleEl = document.getElementById('toast-title');
        const iconEl = document.getElementById('toast-icon');
        const iconBg = document.getElementById('toast-icon-bg');
        const toastBorder = document.getElementById('toast-border');

        messageEl.textContent = decodeURIComponent(msg.replace(/\+/g, ' '));

        // Remove hidden classes (translate-x-[150%])
        toast.classList.remove('translate-x-[150%]', 'opacity-0');

        if (status === 'success') {
            titleEl.textContent = 'Success!';
            titleEl.className = 'text-sm font-bold text-green-400 mb-0.5';
            iconEl.className = 'fas fa-check-circle text-green-400 text-xl';
            iconBg.className = 'inline-flex items-center justify-center flex-shrink-0 w-10 h-10 bg-green-900/50 rounded-lg shadow-sm';
            // Colorful Green Border
            toastBorder.className = 'flex items-center w-full max-w-xs p-4 bg-slate-900 rounded-xl shadow-2xl backdrop-blur-md border border-slate-700 border-l-4 border-l-green-500';
        } else if (status === 'warning') {
            titleEl.textContent = 'Warning';
            titleEl.className = 'text-sm font-bold text-yellow-400 mb-0.5';
            iconEl.className = 'fas fa-exclamation-triangle text-yellow-400 text-xl';
            iconBg.className = 'inline-flex items-center justify-center flex-shrink-0 w-10 h-10 bg-yellow-900/50 rounded-lg shadow-sm';
            // Colorful Yellow Border
            toastBorder.className = 'flex items-center w-full max-w-xs p-4 bg-slate-900 rounded-xl shadow-2xl backdrop-blur-md border border-slate-700 border-l-4 border-l-yellow-500';
        } else {
            // Error (Red)
            titleEl.textContent = 'Error';
            titleEl.className = 'text-sm font-bold text-red-400 mb-0.5';
            iconEl.className = 'fas fa-times-circle text-red-400 text-xl';
            iconBg.className = 'inline-flex items-center justify-center flex-shrink-0 w-10 h-10 bg-red-900/50 rounded-lg shadow-sm';
            // Colorful Red Border
            toastBorder.className = 'flex items-center w-full max-w-xs p-4 bg-slate-900 rounded-xl shadow-2xl backdrop-blur-md border border-slate-700 border-l-4 border-l-red-500';
        }

        // Auto hide after 3 seconds (3000ms)
        setTimeout(() => {
            hideToast();
        }, 3000);
    }

    function hideToast() {
        const toast = document.getElementById('toast-notification');
        // Slide right and fade out
        toast.classList.add('translate-x-[150%]', 'opacity-0');
    }

    // --- Chat Widget Logic ---
    function toggleChat() {
        const widget = document.getElementById('ai-chat-widget');
        const btn = document.getElementById('open-chat-btn');
        if (widget.classList.contains('scale-100')) {
            widget.classList.remove('scale-100');
            widget.classList.add('scale-0');
            setTimeout(() => btn.classList.remove('scale-0', 'opacity-0'), 300);
        } else {
            widget.classList.remove('scale-0');
            widget.classList.add('scale-100');
            btn.classList.add('scale-0', 'opacity-0');
            document.getElementById('chat-input').focus();
        }
    }

    document.getElementById('chat-input').addEventListener('keypress', function (e) {
        if (e.key === 'Enter') sendMessage();
    });

    function sendMessage() {
        const input = document.getElementById('chat-input');
        const message = input.value.trim();
        const chatBox = document.getElementById('chat-messages');
        const sendBtn = document.getElementById('send-btn');

        if (message === '') return;

        input.disabled = true;
        sendBtn.disabled = true;

        const userDiv = document.createElement('div');
        userDiv.className = 'self-end max-w-[85%] p-3 rounded-2xl rounded-br-sm bg-gradient-to-r from-indigo-500 to-purple-600 text-white shadow-md text-sm leading-relaxed animate-fade-in';
        userDiv.textContent = message;
        chatBox.appendChild(userDiv);
        input.value = '';
        chatBox.scrollTop = chatBox.scrollHeight;

        const typingDiv = document.createElement('div');
        typingDiv.className = 'self-start max-w-[85%] p-3 rounded-2xl rounded-bl-sm bg-white text-slate-800 shadow-sm border border-slate-200 text-sm flex gap-1 items-center animate-fade-in';
        typingDiv.id = 'typing-indicator';
        typingDiv.innerHTML = `<div class="w-1.5 h-1.5 bg-slate-400 rounded-full typing-dot" style="animation-delay: -0.32s"></div><div class="w-1.5 h-1.5 bg-slate-400 rounded-full typing-dot" style="animation-delay: -0.16s"></div><div class="w-1.5 h-1.5 bg-slate-400 rounded-full typing-dot"></div>`;
        chatBox.appendChild(typingDiv);
        chatBox.scrollTop = chatBox.scrollHeight;

        const xhr = new XMLHttpRequest();
        xhr.open('POST', '../lib/gemini_chat_handler.php', true);
        xhr.setRequestHeader('Content-type', 'application/x-www-form-urlencoded');
        xhr.onload = function () {
            if (document.getElementById('typing-indicator')) document.getElementById('typing-indicator').remove();
            input.disabled = false;
            sendBtn.disabled = false;
            input.focus();
            if (xhr.status === 200) {
                try {
                    const response = JSON.parse(xhr.responseText);
                    const aiDiv = document.createElement('div');
                    aiDiv.className = 'self-start max-w-[85%] p-3 rounded-2xl rounded-bl-sm bg-white text-slate-800 shadow-sm border border-slate-200 text-sm leading-relaxed animate-fade-in';
                    if (response.error) {
                        aiDiv.innerHTML = '<strong class="text-red-500">Error:</strong> ' + response.error;
                    } else {
                        aiDiv.innerHTML = '<strong class="text-indigo-600 block mb-1">AI:</strong> ' + response.response.replace(/\*\*(.*?)\*\*/g, '<strong class="text-indigo-600">$1</strong>').replace(/\n/g, '<br>');
                    }
                    chatBox.appendChild(aiDiv);
                } catch (e) { console.error(e); }
            }
            chatBox.scrollTop = chatBox.scrollHeight;
        };
        xhr.send('message=' + encodeURIComponent(message));
    }
</script>
