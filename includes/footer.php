<script>
    function toggleChat() {
        const widget = document.getElementById('ai-chat-widget');
        const btn = document.getElementById('open-chat-btn');

        if (widget.classList.contains('scale-100')) {
            widget.classList.remove('scale-100');
            widget.classList.add('scale-0');
            setTimeout(() => {
                btn.classList.remove('scale-0', 'opacity-0');
            }, 300);
        } else {
            widget.classList.remove('scale-0');
            widget.classList.add('scale-100');
            btn.classList.add('scale-0', 'opacity-0');
            document.getElementById('chat-input').focus();
        }
    }

    document.getElementById('chat-input').addEventListener('keypress', function (e) {
        if (e.key === 'Enter') {
            sendMessage();
        }
    });

    function sendMessage() {
        const input = document.getElementById('chat-input');
        const message = input.value.trim();
        const chatBox = document.getElementById('chat-messages');
        const sendBtn = document.getElementById('send-btn');

        if (message === '') return;

        // Disable input
        input.disabled = true;
        sendBtn.disabled = true;

        // Add User Message
        const userDiv = document.createElement('div');
        userDiv.className = 'self-end max-w-[85%] p-3 rounded-2xl rounded-br-sm bg-gradient-to-r from-indigo-500 to-purple-600 text-white shadow-md text-sm leading-relaxed animate-fade-in';
        userDiv.textContent = message;
        chatBox.appendChild(userDiv);

        // Clear input
        input.value = '';
        chatBox.scrollTop = chatBox.scrollHeight;

        // Add Typing Indicator
        const typingDiv = document.createElement('div');
        typingDiv.className = 'self-start max-w-[85%] p-3 rounded-2xl rounded-bl-sm bg-white text-slate-800 shadow-sm border border-slate-200 text-sm flex gap-1 items-center animate-fade-in';
        typingDiv.id = 'typing-indicator';
        typingDiv.innerHTML = `
            <div class="w-1.5 h-1.5 bg-slate-400 rounded-full typing-dot" style="animation-delay: -0.32s"></div>
            <div class="w-1.5 h-1.5 bg-slate-400 rounded-full typing-dot" style="animation-delay: -0.16s"></div>
            <div class="w-1.5 h-1.5 bg-slate-400 rounded-full typing-dot"></div>
        `;
        chatBox.appendChild(typingDiv);
        chatBox.scrollTop = chatBox.scrollHeight;

        // Send AJAX Request
        const xhr = new XMLHttpRequest();
        xhr.open('POST', '../lib/gemini_chat_handler.php', true);
        xhr.setRequestHeader('Content-type', 'application/x-www-form-urlencoded');

        xhr.onload = function () {
            // Remove typing indicator
            const indicator = document.getElementById('typing-indicator');
            if (indicator) indicator.remove();

            // Enable input
            input.disabled = false;
            sendBtn.disabled = false;
            input.focus();

            if (xhr.status === 200) {
                try {
                    const response = JSON.parse(xhr.responseText);
                    const aiDiv = document.createElement('div');
                    aiDiv.className = 'self-start max-w-[85%] p-3 rounded-2xl rounded-bl-sm bg-white text-slate-800 shadow-sm border border-slate-200 text-sm leading-relaxed animate-fade-in';

                    if (response.error) {
                        aiDiv.innerHTML = '<strong class="text-red-500">Error:</strong> ' + response.error;
                    } else {
                        // Format bold text
                        let formattedText = response.response
                            .replace(/\*\*(.*?)\*\*/g, '<strong class="text-indigo-600">$1</strong>')
                            .replace(/\n/g, '<br>');
                        aiDiv.innerHTML = '<strong class="text-indigo-600 block mb-1">AI:</strong> ' + formattedText;
                    }
                    chatBox.appendChild(aiDiv);
                } catch (e) {
                    console.error('JSON Parse Error', e);
                }
            } else {
                const errorDiv = document.createElement('div');
                errorDiv.className = 'self-start max-w-[85%] p-3 rounded-2xl rounded-bl-sm bg-white text-red-500 shadow-sm border border-red-200 text-sm animate-fade-in';
                errorDiv.innerHTML = '<strong>Error:</strong> Connection failed.';
                chatBox.appendChild(errorDiv);
            }
            chatBox.scrollTop = chatBox.scrollHeight;
        };

        xhr.onerror = function () {
            const indicator = document.getElementById('typing-indicator');
            if (indicator) indicator.remove();

            input.disabled = false;
            sendBtn.disabled = false;

            const errorDiv = document.createElement('div');
            errorDiv.className = 'self-start max-w-[85%] p-3 rounded-2xl rounded-bl-sm bg-white text-red-500 shadow-sm border border-red-200 text-sm animate-fade-in';
            errorDiv.innerHTML = '<strong>Error:</strong> Network error.';
            chatBox.appendChild(errorDiv);
        };

        xhr.send('message=' + encodeURIComponent(message));
    }
</script>

